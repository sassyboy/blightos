///
/// Generic Framebuffer driver
/// 
/// Offers basic pixel/char drawing
/// 
/// Instantiated by a VGA/VideoCore driver.
/// Only one framebuffer per machine. No multiple screen support
/// 

use core::mem::size_of;
use core::cmp::min;
use alloc::{format, slice};
use alloc::string::String;
use crate::fs::{DirectoryEntry, FileOperation, MountPoint};
use crate::util::*;
use crate::Error;

pub type RGB = (u8, u8, u8);

#[derive(Copy, Clone)]
pub struct FrameBuffer {
	pub base_address:   	usize,
    pub pitch:          	u32,    // total # of bytes in one horizontal line
    pub width:          	u32,    // in pixels
    pub height:         	u32,    // in pixels
    pub bpp:            	u8,     // bits/pixel
    pub red_field_position: u8,
    pub red_mask_size:      u8,
    pub green_field_position: u8,
    pub green_mask_size:    u8,
    pub blue_field_position:u8,
    pub blue_mask_size:     u8,
	pub background_rgb:     RGB,
    pub foreground_rgb:     RGB,
	enabled:				bool
}

static DEFAULT_FB:	Spinlock<FrameBuffer> = Spinlock::new(FrameBuffer::new());

impl FrameBuffer {
	//
	// Public Interface
	//
    pub const fn new() -> Self {
        Self {
        	base_address:   		0,
        	pitch:          		0,
        	width:          		0,
        	height:         		0,
        	bpp:            		0,
        	red_field_position: 	0,
    		red_mask_size:      	0,
    		green_field_position: 	0,
    		green_mask_size:    	0,
    		blue_field_position:	0,
    		blue_mask_size:     	0,
            background_rgb:     	(0, 0, 0),
            foreground_rgb:     	(200, 200, 200),
			enabled:				false
        }
    }

	pub fn enabled() -> bool {
		let fb = DEFAULT_FB.lock();
		fb.enabled
	}

	pub fn screen_size() -> (u32, u32) {
		let fb = DEFAULT_FB.lock();
		if fb.enabled {
			return (fb.height, fb.width) // rows, columns
		}
        (0, 0)
    }

	pub fn font_size() -> (u32, u32) {
		let fb = DEFAULT_FB.lock();
		if fb.enabled {
			return (20, 10); // rows, columns
		}
        (0, 0)
    }

	pub fn set_background_rgb(bg: RGB) {
		let mut fb = DEFAULT_FB.lock();
        fb.background_rgb = bg;
    }

	pub fn get_background_rgb() -> RGB {
		let fb = DEFAULT_FB.lock();
		fb.background_rgb
	}

	pub fn set_foreground_rgb(fg: RGB) {
		let mut fb = DEFAULT_FB.lock();
        fb.foreground_rgb = fg;
    }

	pub fn get_foreground_rgb() -> RGB {
		let fb = DEFAULT_FB.lock();
		fb.foreground_rgb
	}

	pub fn clean_screen() {
		let mut fb = DEFAULT_FB.lock();
		if fb.enabled {
			let bg = fb.background_rgb;
    		for r in 0..fb.height {
        		for c in 0..fb.width {
            		fb.set_pixel_locked(r, c, bg);
        		}
    		}
		}
		
    }
	
	pub fn putc(c: u8, row: u32, col: u32) {
		let mut fb = DEFAULT_FB.lock();
		if fb.enabled {
			let fg = fb.foreground_rgb;
			let bg = fb.background_rgb;
        	for y in 0..20 as u32 {
        		for x in 0..10 as u32 {
            		let fmi = (c as usize) * 40 + (y * 16 + x) as usize / 8;
            		if VGA_FONT10X20[fmi] & (1 << ((y * 16 + x) % 8)) > 0 {
                		fb.set_pixel_locked(row * 20 + y, col * 10 + x, fg);
            		} else {
                		fb.set_pixel_locked(row * 20 + y, col * 10 + x, bg);
            		}
        		}
    		}
		}
    }

	pub fn set_pixel(row: u32, col: u32, rgb: (u8, u8, u8)) {
		let mut fb = DEFAULT_FB.lock();
		if fb.enabled {
			fb.set_pixel_locked(row, col, rgb);
		}
	}

	//
	// Private interface
	//
	fn set_pixel_locked(&mut self, row: u32, col: u32, rgb: (u8, u8, u8)){
    	unsafe {
        	if self.bpp != 32 && self.bpp != 24 {
            	return; // Unsupported color depth
        	}
        	if row >= self.height ||
				col >= self.width {
            return; // Out of bounds
        	}

        	let pixel_offset = self.base_address as usize + 
                        	self.pitch as usize * row as usize +
                        	(self.bpp as usize/8) * col as usize;
        	let mut bufp : *mut u8 = pixel_offset as *mut u8;
        	*bufp = rgb.2;
        	bufp = bufp.wrapping_add(1);
        	*bufp = rgb.1;
        	bufp = bufp.wrapping_add(1);
        	*bufp = rgb.0;
    	}
	}

	// 
	// VGA/VideoCore Interface
	//
	pub fn register(info: &FrameBuffer) {
		let mut fb = DEFAULT_FB.lock();
		*fb = info.clone();
		fb.enabled = true;
	}

	//
	// Driver Interface
	//
	pub fn enumerate() -> usize {
		// Register a mount-point for user-space access
        let mnt_obj = MountPoint {
            name:       String::from("framebuffer"),
            fops:       Self::fops_handler
        };
        if MountPoint::mount(mnt_obj) {
            return 1;
        }
        0
    }

    pub fn post_enum() {

    }

    pub fn release(_dev_id: usize) {

    }

	//
	// VFS Interface
	//
	// Read: Returns the framebuffer information as string
	// Write: Nout supported
	// Exec: See FUNC_ constants below
	//
	pub const DEV_HANDLE_DEFAULT:       usize = 1;
	// Returns the framebuffer information as a FrameBufferInfo struct
	pub const FUNC_GET_INFO:         	usize = 1;
	// Saves the current framebuffer content into a buffer provided by
	// user-space. The buffer should be large enough to hold the entire
	// framebuffer content (pitch * height * bpp/8 bytes).
	pub const FUNC_SAVE_FRAME:	 		usize = 2;
	pub const FUNC_RESTORE_FRAME: 		usize = 3;
	// Updates a rectangular region of the framebuffer with pixel data provided
	// by user-space. The user-space buffer should contain pixel data for the
	// specified rectangle (width * height * bpp/8 bytes).
	pub const FUNC_UPDATE_RECT: 		usize = 4;
	fn fops_handler(op: FileOperation) -> Result<usize, Error> {
        match op {
            FileOperation::Open { full_path, mode: _, dent } => {
                let mpath = MountPoint::device_relative_path(full_path);
                if mpath.eq("/") {
					dent.name = String::from("");
					dent.size = 0; // TODO: return the actual size
					dent.flags = DirectoryEntry::DEV_RWX_DIR_FLAGS;
                    return Ok(Self::DEV_HANDLE_DEFAULT);
                } else {
                    return Err(error!(ErrorCode::InvalidPath));
                }
                
            },
            FileOperation::Close { hnd }                    => {
                if hnd == Self::DEV_HANDLE_DEFAULT {
                    return Ok(0);
                }
                return  Err(error!(ErrorCode::InvalidHandle));
            },
            FileOperation::Read { hnd, off, buff } 	=> {
                return Self::fread(hnd, off, buff);
            },
			FileOperation::Exec { hnd, func, buff }         	=> {
                if hnd != Self::DEV_HANDLE_DEFAULT {
                    return  Err(error!(ErrorCode::InvalidHandle));
                }
                match func {
                    Self::FUNC_GET_INFO           => {
                        return Self::fexec_get_info(hnd, buff);
                    },
                    Self::FUNC_SAVE_FRAME => {
                        return Self::fexec_save_frame(hnd, buff);
                    },
					Self::FUNC_RESTORE_FRAME => {
						return Self::fexec_restore_frame(hnd, buff);
					},
					Self::FUNC_UPDATE_RECT => {
						return Self::fexec_update_rect(hnd, buff);
					},
                    _       => {
                        return  Err(error!(ErrorCode::InvalidOp));
                    }
                }
            },
            _                                               => {
                return Err(error!(ErrorCode::InvalidOp));
            }
        }
    }

	fn fread(hnd: usize, off: usize, buff: &mut [u8]) -> Result<usize, Error> {
		let fb = DEFAULT_FB.lock();
		if !fb.enabled {
			return Err(error!(ErrorCode::IOError));
		}
        if hnd == Self::DEV_HANDLE_DEFAULT {
            let out = format!(
                "Width : {}\n\
                 Height: {}\n\
				 BPP   : {}\n\
				 Pitch : {}",
                fb.width, fb.height, fb.bpp, fb.pitch
            );
            let len = min(out[off..].len(), buff.len());
            let ptr = out[off..].as_ptr();
            unsafe {
                buff[0..len].copy_from_slice(slice::from_raw_parts(ptr, len));
            }
            return Ok(len);
        }
        Err(error!(ErrorCode::InvalidOp))
    }

	fn fexec_get_info(hnd: usize, buff: &mut [u8]) -> Result<usize, Error> {
		let fb = DEFAULT_FB.lock();
		if !fb.enabled {
			return Err(error!(ErrorCode::IOError));
		}
		if hnd == Self::DEV_HANDLE_DEFAULT {
			if buff.len() < size_of::<FrameBufferInfo>() {
				return Err(error!(ErrorCode::InvalidBuffer));
			}
			let info = FrameBufferInfo {
				height: fb.height,
				width:  fb.width,
				bpp:    fb.bpp as u8,
				pitch:  fb.pitch
			};
			let ptr = &info as *const FrameBufferInfo as *const u8;
			unsafe {
				buff[0..size_of::<FrameBufferInfo>()].copy_from_slice(
					slice::from_raw_parts(ptr, size_of::<FrameBufferInfo>()));
			}
			return Ok(size_of::<FrameBufferInfo>());
		}
		Err(error!(ErrorCode::InvalidOp))
	}

	fn fexec_save_frame(hnd: usize, buff: &mut [u8]) -> Result<usize, Error> {
		if hnd != Self::DEV_HANDLE_DEFAULT {
			return Err(error!(ErrorCode::InvalidHandle));
		}
		let fb = DEFAULT_FB.lock();
		if !fb.enabled {
			return Err(error!(ErrorCode::IOError));
		}

		let frame_size = (fb.pitch * fb.height) as usize;
		if buff.len() < frame_size {
			return Err(error!(ErrorCode::InvalidBuffer));
		}

		unsafe {
			let src = fb.base_address as *const u8;
			let dst = buff.as_mut_ptr() as *mut u8;
			core::ptr::copy_nonoverlapping(src, dst, frame_size);
		}
		Ok(frame_size)
	}

	fn fexec_restore_frame(hnd: usize, buff: &mut [u8]) -> Result<usize, Error>{
		if hnd != Self::DEV_HANDLE_DEFAULT {
			return Err(error!(ErrorCode::InvalidHandle));
		}
		let fb = DEFAULT_FB.lock();
		if !fb.enabled {
			return Err(error!(ErrorCode::IOError));
		}

		let frame_size = (fb.pitch * fb.height) as usize;
		if buff.len() < frame_size {
			return Err(error!(ErrorCode::InvalidBuffer));
		}

		unsafe {
			let src = buff.as_ptr() as *const u8;
			let dst = fb.base_address as *mut u8;
			core::ptr::copy_nonoverlapping(src, dst, frame_size);
		}
		Ok(frame_size)
	}

	fn fexec_update_rect(hnd: usize, buff: &mut [u8]) -> Result<usize, Error> {
		if hnd != Self::DEV_HANDLE_DEFAULT {
			return Err(error!(ErrorCode::InvalidHandle));
		}
		if buff.len() < size_of::<FrameBufferUpdateRectArgs>() {
			return Err(error!(ErrorCode::InvalidBuffer));
		}
		let args = unsafe {
			(buff.as_ptr() as *const FrameBufferUpdateRectArgs).read()
		};
		let rect = args.rect;
		let buffer_base = args.buffer_base;
		let buffer_size = args.buffer_size;
		let flags = args.flags;

		let mut fb = DEFAULT_FB.lock();
		if !fb.enabled {
			return Err(error!(ErrorCode::IOError));
		}

		if buffer_size < (rect.height * rect.width * (fb.bpp / 8) as u32) {
			return Err(error!(ErrorCode::InvalidBuffer));
		}

		let pixel_data = unsafe {
			slice::from_raw_parts(buffer_base as *const u8, buffer_size as usize)
		};

		for r in 0..rect.height {
			for c in 0..rect.width {
				let idx;
				if flags & FrameBufferUpdateRectArgs::FLAG_FULL_FRAME > 0 {
					// The input buffer contains a full frame.
					// We should calculate the pixel position based on the
					// rectangle's position within the framebuffer.
					let row = rect.row + r;
					let col = rect.col + c;
					if row < fb.height && col < fb.width {
						idx = ((row * fb.pitch + col * (fb.bpp as u32 / 8)) as usize) as usize;
					} else {
						continue; // Skip out-of-bounds pixels
					}
				} else {
					// The input buffer contains only the pixel data for the
					// specified rectangle.
					idx = ((r * rect.width + c) * 4) as usize;
				}
				if idx + 3 >= pixel_data.len() {
					return Err(error!(ErrorCode::InvalidBuffer));
				}
				let rgb = (
					pixel_data[idx],
					pixel_data[idx + 1],
					pixel_data[idx + 2]
				);
				fb.set_pixel_locked(rect.row + r, rect.col + c, rgb);
			}
		}

		return Ok(0);
	}
}

//
// VFS Function Structures
//
#[repr(C, packed)]
pub struct FrameBufferInfo {
	pub height: u32,
	pub width: 	u32,
	pub bpp: 	u8,
	pub pitch: 	u32
}
#[repr(C, packed)]
pub struct FrameBufferRect {
	pub row: 	u32,
	pub col: 	u32,
	pub height: u32,
	pub width: 	u32
}
#[repr(C, packed)]
pub struct FrameBufferUpdateRectArgs {
	pub rect: 			FrameBufferRect,
	// User-buffer address containing pixel data (bpp-bytes) for the specified
	// rectangle.
	pub buffer_base: 	usize,
	pub buffer_size: 	u32,
	// Flags: Whether the buffer is a full framebuffer dump or just the updated
	// rectangle. This can help the driver optimize the update process.
	pub flags: 			u32
}
impl FrameBufferUpdateRectArgs {
	pub const FLAG_FULL_FRAME: u32 = 1;
}
